def detect_system_language():
    # 1. Check saved preferences first
    if PREF_FILE.exists():
        try:
            data = json.loads(PREF_FILE.read_text(encoding="utf-8"))
            if data.get("app_language") in LANGUAGES:
                return data["app_language"]
        except Exception:
            pass

    # 2. Check Windows UI language ID
    try:
        lang_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        # Primary language ID is the lower 10 bits: lang_id & 0x3ff
        primary = lang_id & 0x3ff
        mapping = {
            0x09: "en", # English
            0x0c: "fr", # French
            0x07: "de", # German
            0x11: "ja", # Japanese
            0x0a: "es", # Spanish
            0x10: "it", # Italian
            0x16: "pt", # Portuguese
            0x04: "zh", # Chinese
            0x01: "ar", # Arabic
            0x19: "ru", # Russian
        }
        if primary in mapping:
            return mapping[primary]
    except Exception:
        pass

    # 3. Fallback to locale
    try:
        loc = locale.getdefaultlocale()[0]
        if loc:
            prefix = loc.split("_")[0].lower()
            if prefix in LANGUAGES:
                return prefix
    except Exception:
        pass

    return "en"

def set_saved_language(lang_code):
    if lang_code in LANGUAGES:
        try:
            data = {}
            if PREF_FILE.exists():
                data = json.loads(PREF_FILE.read_text(encoding="utf-8"))
            data["app_language"] = lang_code
            PREF_FILE.write_text(json.dumps(data, indent=2), encoding="utf-8")
        except Exception:
            pass

def get_text(key, lang="en", **kwargs):
    # Fallback order: lang -> en -> key
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS.get("en", {}))
    txt = lang_dict.get(key, TRANSLATIONS.get("en", {}).get(key, key))
    if kwargs:
        try:
            return txt.format(**kwargs)
        except Exception:
            return txt
    return txt

